package com.beatgridmedia.measurementkit.persistence.entity;

import jakarta.persistence.Column;
import jakarta.persistence.Entity;
import jakarta.persistence.EnumType;
import jakarta.persistence.Enumerated;
import jakarta.persistence.FetchType;
import jakarta.persistence.JoinColumn;
import jakarta.persistence.ManyToOne;
import jakarta.persistence.Table;
import lombok.Getter;
import lombok.NoArgsConstructor;
import lombok.Setter;
import org.beatkit.persistence.entity.AbstractEntity;
import org.hibernate.annotations.JdbcTypeCode;
import org.hibernate.type.SqlTypes;

import java.time.Instant;

/**
 * An app installation. May exist before a user has logged in on it.
 */
@Entity
@Table(name = "devices")
@Getter
@Setter
@NoArgsConstructor
public class DeviceEntity extends AbstractEntity {

    /**
     * Random identifier generated by the app on first launch.
     */
    @Column(nullable = false, unique = true, length = 64)
    private String installationId;

    @Enumerated(EnumType.STRING)
    @JdbcTypeCode(SqlTypes.VARCHAR)
    @Column(nullable = false, length = 16)
    private DevicePlatform platform;

    @Column(length = 32)
    private String appVersion;

    @Column(length = 32)
    private String osVersion;

    /**
     * The user currently logged in on this device, if any.
     */
    @ManyToOne(fetch = FetchType.LAZY)
    @JoinColumn(name = "user_id")
    private UserEntity user;

    private Instant lastSeenAt;
}
